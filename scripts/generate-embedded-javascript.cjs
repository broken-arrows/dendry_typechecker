// Regenerate the shipped guest grammar after changing the pinned source or guards:
// node scripts/generate-embedded-javascript.cjs
const { readFileSync, writeFileSync } = require('node:fs');
const { resolve } = require('node:path');

// A capture-free, permissive copy used only to find candidate match positions.
// Keeping the original regex in front of the absent stopper lets Oniguruma use
// its normal search optimizations instead of retrying a large JS regex at every
// character in the rest of a long rich-content line.
function searchPattern(regex) {
  let result = '';
  let classStart = -1;
  const extended = /^\(\?[a-z]*x[a-z]*\)/.test(regex);
  for (let index = 0; index < regex.length; index++) {
    const character = regex[index];
    if (character === '\\') {
      if (classStart < 0 && /[1-9]/.test(regex[index + 1] || '')) {
        // A prefilter must never reject a possible match. The consuming regex
        // below retains the real backreference and all original captures.
        while (/[0-9]/.test(regex[index + 1] || '')) index++;
        result += '[\\s\\S]*?';
      } else {
        result += character + regex[++index];
      }
    } else if (classStart >= 0) {
      if (character === '[' && regex[index + 1] === ':') {
        const end = regex.indexOf(':]', index + 2);
        if (end < 0) throw new Error('Unclosed POSIX character class');
        result += regex.slice(index, end + 2);
        index = end + 1;
      } else {
        result += character;
        const firstCharacter = classStart + (regex[classStart + 1] === '^' ? 2 : 1);
        if (character === ']' && index > firstCharacter) classStart = -1;
      }
    } else if (character === '[') {
      classStart = index;
      result += character;
    } else if (extended && character === '#') {
      const end = regex.indexOf('\n', index);
      if (end < 0) { result += regex.slice(index); break; }
      result += regex.slice(index, end + 1);
      index = end;
    } else if (character === '(' && regex[index + 1] !== '?') {
      result += '(?:';
    } else {
      if (character === '(' && regex.startsWith('(?<', index) && !/[=!]/.test(regex[index + 3])) {
        throw new Error('Named guest captures need a capture-free search pattern');
      }
      result += character;
    }
  }
  return result;
}

function boundedRules(source, close) {
  // Noncapturing wrappers preserve the upstream capture numbers/backreferences.
  // In extended mode a newline keeps a trailing (# ...) comment from eating ')'.
  const wrap = regex => `(?:${regex}${/^\(\?[a-z]*x[a-z]*\)/.test(regex) ? '\n' : ''})`;
  const bounded = regex => `(?=${wrap(searchPattern(regex))})(?~|${close})${wrap(regex)}`;
  const copy = JSON.parse(JSON.stringify(source));
  function visit(rule) {
    if (!rule || typeof rule !== 'object') return;
    for (const key of ['begin', 'match']) {
      if (typeof rule[key] === 'string') rule[key] = bounded(rule[key]);
    }
    // Every guest stack frame must unwind at the *start* of the host delimiter.
    // Guarding only the outer embedding leaves return/string/comment rules open.
    if (typeof rule.end === 'string') rule.end = `(?=${close})|${bounded(rule.end)}`;
    // The pinned grammar has no while rules; fail rather than silently lose the
    // boundary guarantee if an upstream update introduces one.
    if (rule.while !== undefined) throw new Error('Guest while rules need a boundary guard');
    for (const value of Object.values(rule)) visit(value);
  }
  visit(copy);
  return { patterns: copy.patterns, repository: copy.repository };
}

function generate(source) {
  return {
    name: 'Dendry embedded JavaScript',
    scopeName: 'source.dendry.javascript',
    version: source.version,
    comment: 'Generated by scripts/generate-embedded-javascript.cjs. Microsoft MIT license: LICENSE.javascript.txt. Do not edit by hand.',
    patterns: [{ include: '#property' }],
    repository: {
      property: boundedRules(source, '!\\}'),
      // Content escaping differs from executable property delimiters upstream.
      content: boundedRules(source, '(?<!\\\\)!\\}'),
    },
  };
}

module.exports = { generate };
if (require.main === module) {
  const root = resolve(__dirname, '..');
  const source = JSON.parse(readFileSync(resolve(root, 'src/test-fixtures/javascript/JavaScript.tmLanguage.json'), 'utf8'));
  writeFileSync(resolve(root, 'syntaxes/dendry-javascript.tmLanguage.json'), JSON.stringify(generate(source), null, 2) + '\n');
}
